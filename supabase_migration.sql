-- ---- Feature 1: Shopping list manual reordering --------------
alter table shopping_list add column if not exists position numeric;

-- ---- Feature 2: Per-recipe nutrition (totals for whole recipe)
alter table recipes add column if not exists calories numeric;
alter table recipes add column if not exists protein  numeric;
alter table recipes add column if not exists carbs    numeric;
alter table recipes add column if not exists fat      numeric;

-- ---- Feature 3: Folders (a recipe can belong to many folders) -
create table if not exists folders (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null
);

create table if not exists recipe_folders (
  id bigint generated by default as identity primary key,
  recipe_id bigint references recipes(id) on delete cascade not null,
  folder_id bigint references folders(id) on delete cascade not null,
  unique (recipe_id, folder_id)
);

-- Enable Row Level Security on the new tables
alter table folders        enable row level security;
alter table recipe_folders enable row level security;

-- Access policies (any logged-in user can manage their data)
do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'folders' and policyname = 'Allow authenticated users') then
    create policy "Allow authenticated users" on folders for all using (auth.role() = 'authenticated');
  end if;
  if not exists (select 1 from pg_policies where tablename = 'recipe_folders' and policyname = 'Allow authenticated users') then
    create policy "Allow authenticated users" on recipe_folders for all using (auth.role() = 'authenticated');
  end if;
end $$;
